import {LabGestures} from '../src/hands/labGestures';
import {ScreenStabilizer} from '../src/utils/stability';
import type {HandFrame} from '../src/hands/handFrame';
import type {ToyFrame,ToyContext,LabEvent} from '../src/playlab/types';
import orb from '../src/playlab/toys/energyOrb';
import fireworks from '../src/playlab/toys/fireworks';
import * as THREE from 'three';
import {mkdirSync,writeFileSync} from 'node:fs';
const results:{name:string;pass:boolean}[]=[];
const check=(name:string,pass:boolean)=>{results.push({name,pass});console.log(`${pass?'PASS':'FAIL'} ${name}`);};
const stable=new ScreenStabilizer();stable.update({x:200,y:300});
check('stationary CSS noise does not accumulate drift',Array.from({length:300},(_,i)=>stable.update({x:200+Math.sin(i)*1.2,y:300+Math.cos(i)*1.2})).every(p=>p.x===200&&p.y===300));
check('intentional movement has no trailing offset',stable.update({x:204,y:300}).x===204);
stable.reset();check('identity reset accepts a fresh anchor',stable.update({x:900,y:600}).x===900);
const hand=(role:'primary'|'secondary',state:HandFrame['pinchState']):HandFrame=>({role,handedness:role==='primary'?'Right':'Left',confidence:1,landmarks:[],worldLandmarks:null,palmCenter:{x:.5,y:.5,z:0},palmNormal:{x:0,y:0,z:1},facing:1,palmWidth:.15,palmVelocity:{x:0,y:0,z:0},palmAcceleration:{x:0,y:0,z:0},openness:.2,grabStrength:1,wristRotation:0,pinchState:state,pinchPoint:{x:.5,y:.5,z:0},pinchStrength:1,isStable:true,visibleForMs:2000});
let at=0;
const frame=(p:HandFrame|null,s:HandFrame|null,interactive=true,epoch=1):ToyFrame=>({at:at+=33,dt:.033,primary:p,secondary:s,two:null,pointer:{x:.5,y:.5,z:0},pinching:p?.pinchState==='HOLD',interactive,quality:'performance',night:0,reducedMotion:true,idleFor:0,handEpoch:epoch});
const detector=new LabGestures();let messages:{event:LabEvent;frame:ToyFrame}[]=[];
detector.subscribe((event,f)=>messages.push({event,frame:f}));
detector.update(frame(hand('primary','NEAR'),hand('secondary','CONTACT')));
check('NEAR and candidate CONTACT produce no pinch',messages.every(m=>!m.event.startsWith('PINCH')));
messages=[];detector.update(frame(hand('primary','HOLD'),hand('secondary','OPEN')));
check('primary START cannot start secondary',messages.filter(m=>m.event==='PINCH_START').length===1&&messages[0].frame.gesture?.role==='primary');
const firstSession=messages[0].frame.gesture?.sessionId;
messages=[];detector.update(frame(hand('primary','HOLD'),hand('secondary','HOLD')));
check('secondary can independently START',messages.some(m=>m.event==='PINCH_START'&&m.frame.gesture?.role==='secondary'));
check('held primary keeps session ID',messages.some(m=>m.event==='PINCH_HOLD'&&m.frame.gesture?.sessionId===firstSession));
messages=[];detector.update(frame(hand('primary','RELEASE'),hand('secondary','HOLD')));
check('primary release does not end secondary',messages.filter(m=>m.event==='PINCH_END').every(m=>m.frame.gesture?.role==='primary'));
messages=[];detector.update(frame(hand('primary','OPEN'),hand('secondary','HOLD'),false));
check('UI capture cancels secondary',messages.some(m=>m.event==='PINCH_END'&&m.frame.gesture?.cancelled));
messages=[];detector.update(frame(hand('primary','OPEN'),hand('secondary','HOLD')));
check('held pinch cannot restart after UI capture',!messages.some(m=>m.event==='PINCH_START'));
detector.update(frame(hand('primary','OPEN'),hand('secondary','OPEN')));
messages=[];detector.update(frame(hand('primary','OPEN'),hand('secondary','HOLD')));
check('fresh secondary pinch after release restarts',messages.some(m=>m.event==='PINCH_START'));
messages=[];detector.update(frame(hand('primary','OPEN'),null));
check('loss cancels instead of throwing',messages.some(m=>m.event==='PINCH_END'&&m.frame.gesture?.cancelled));
detector.update(frame(hand('primary','OPEN'),hand('secondary','OPEN')));
detector.update(frame(hand('primary','OPEN'),hand('secondary','HOLD')));
messages=[];detector.update(frame(hand('primary','OPEN'),hand('secondary','HOLD'),true,2));
check('identity epoch ends grab without immediate recapture',messages.some(m=>m.event==='PINCH_END'&&m.frame.gesture?.cancelled)&&!messages.some(m=>m.event==='PINCH_START'));
const ctx={id:'orb',quality:'performance',volume:{width:16,height:9,depth:3},root:new THREE.Group(),scene:new THREE.Scene(),camera:new THREE.PerspectiveCamera(),toWorld:()=>({x:0,y:.2,z:0}),notify:()=>{},emit:()=>{}} as ToyContext;
const isolated=frame(hand('primary','OPEN'),hand('secondary','HOLD'));
isolated.gesture={role:'secondary',handId:'1:Left',sessionId:7,state:'START',cancelled:false};
orb.enter(ctx);orb.onGesture('PINCH_START',isolated);
const bodies=(orb as unknown as {bodies:{grabbed:string}[]}).bodies;
check('orb secondary-only grab belongs to secondary',bodies[0].grabbed==='secondary');
orb.onGesture('PINCH_END',{...isolated,secondary:null,gesture:{...isolated.gesture,state:'END',cancelled:true}});
check('orb loss releases missing hand',bodies[0].grabbed==='none');orb.dispose();
const fireCtx={...ctx,id:'fireworks'} as ToyContext;
fireworks.enter(fireCtx);fireworks.update(isolated,fireCtx);fireworks.onGesture('PINCH_START',isolated);
const fire=fireworks as unknown as {charge:{role:string}[];cursor:number};
check('fireworks secondary alone charges only secondary',fire.charge.length===1&&fire.charge[0].role==='secondary');
fireworks.onGesture('PINCH_END',{...isolated,gesture:{...isolated.gesture,state:'END',cancelled:false}});
check('fireworks secondary alone launches',fire.cursor>0&&fire.charge.length===0);
fireworks.onGesture('PINCH_START',isolated);const count=fire.cursor;
fireworks.onGesture('PINCH_END',{...isolated,gesture:{...isolated.gesture,state:'END',cancelled:true}});
check('fireworks cancellation has no burst',fire.cursor===count&&fire.charge.length===0);fireworks.dispose();
mkdirSync('docs/verification',{recursive:true});writeFileSync('docs/verification/phase17-core.json',JSON.stringify({input:'synthetic Node hand frames, no camera/GPU',results},null,2));
if(results.some(r=>!r.pass))process.exitCode=1;
